# The parameters of Xenia's xam exports (each one's _entry function in
# xenia-canary's src/xenia/kernel/xam/*.cc, BSD; see LICENSE-xenia), with how
# Xenia marks its own implementation (kImplemented, kSketchy, kStub), as a C++
# table for xfxam's survey (tools/xam_signatures.inc), which makes each
# export's arguments from them. Only the parameters' types and names are
# taken: facts about the calls, not code.
#
#   python tools/xam_signatures.py ../xenia-canary tools/xam_signatures.inc

import re
import sys
from pathlib import Path

HEADER = """\
/**
 ******************************************************************************
 * Xenia : Xbox 360 Emulator Research Project                                 *
 ******************************************************************************
 * Copyright 2022 Ben Vanik. All rights reserved.                             *
 * Released under the BSD license - see LICENSE in the root for more details. *
 ******************************************************************************
 */

// Generated by tools/xam_signatures.py from xenia-canary's
// src/xenia/kernel/xam/*.cc: each xam export's parameters (type and name, as
// Xenia declares its _entry function) and Xenia's mark for its own
// implementation (0 implemented, 1 sketchy, 2 stub). Not edited by hand.
//
//   XF_XAM_SIGNATURE(name, mark, "type name, type name, ...")
"""

ENTRY = re.compile(r"\b(\w+)_entry\s*\(([^)]*)\)\s*\{", re.S)
DECLARE = re.compile(r"DECLARE_XAM_EXPORT[12]?\(\s*(\w+)\s*,\s*\w+\s*,([^)]*)\)")


def main():
    xenia, out = Path(sys.argv[1]), Path(sys.argv[2])
    sources = sorted((xenia / "src/xenia/kernel/xam").glob("*.cc"))
    entries, marks = {}, {}
    for source in sources:
        text = source.read_text(encoding="utf-8", errors="replace")
        for m in ENTRY.finditer(text):
            params = []
            for p in m.group(2).split(","):
                p = " ".join(p.split())
                if not p or p.startswith("const ppc_context_t") or p == "void":
                    continue
                params.append(p)
            entries.setdefault(m.group(1), params)
        for m in DECLARE.finditer(text):
            flags = m.group(2)
            marks[m.group(1)] = 2 if "kStub" in flags else 1 if "kSketchy" in flags else 0
    lines = [HEADER]
    for name in sorted(marks):
        if name not in entries:
            continue
        lines.append('XF_XAM_SIGNATURE(%s, %d, "%s")\n' % (name, marks[name], ", ".join(entries[name])))
    out.write_text("".join(lines), encoding="utf-8", newline="\n")
    print("%d signatures" % (len(lines) - 1))


if __name__ == "__main__":
    main()
