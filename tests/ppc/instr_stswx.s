# Store string word: stswi (count in the instruction) and stswx (count in
# XER[57:63], set with mtxer). Xenia has neither, nor tests for them; these
# follow PowerPC Book I. Same format as Xenia's tests (src/xenia/cpu/ppc/testing).

test_stswi_1:
  #_ MEMORY_IN 10001000 AAAAAAAAAAAAAAAA
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r7 0xFFFFFFFF11223344
  #_ REGISTER_IN r8 0x5566778899AABBCC
  stswi r7, r4, 5
  blr
  #_ MEMORY_OUT 10001000 1122334499AAAAAA

test_stswi_32:
  #_ MEMORY_IN 10001020 AAAAAAAA
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r7 0x0000000000010203
  #_ REGISTER_IN r8 0x0000000004050607
  #_ REGISTER_IN r9 0x0000000008090A0B
  #_ REGISTER_IN r10 0x000000000C0D0E0F
  #_ REGISTER_IN r11 0x0000000010111213
  #_ REGISTER_IN r12 0x0000000014151617
  #_ REGISTER_IN r13 0x0000000018191A1B
  #_ REGISTER_IN r14 0x000000001C1D1E1F
  #_ REGISTER_IN r15 0x0000000020212223
  stswi r7, r4, 0
  blr
  #_ MEMORY_OUT 10001000 000102030405060708090A0B0C0D0E0F101112131415161718191A1B1C1D1E1FAAAAAAAA

test_stswi_wrap:
  #_ MEMORY_IN 10001000 AAAAAAAAAAAAAAAAAAAAAAAA
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r30 0x0000000001020304
  #_ REGISTER_IN r31 0x0000000005060708
  #_ REGISTER_IN r0 0x00000000090A0B0C
  stswi r30, r4, 10
  blr
  #_ MEMORY_OUT 10001000 0102030405060708090AAAAA

test_stswx_1:
  #_ MEMORY_IN 10001000 AAAAAAAAAAAAAAAA
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r5 0x0000000000000001
  #_ REGISTER_IN r6 0x0000000000000006
  #_ REGISTER_IN r7 0xFFFFFFFF11223344
  #_ REGISTER_IN r8 0x5566778899AABBCC
  mtxer r6
  stswx r7, r4, r5
  blr
  #_ MEMORY_OUT 10001000 AA1122334499AAAA

test_stswx_ra0:
  #_ MEMORY_IN 10001000 AAAAAAAAAAAAAAAA
  #_ REGISTER_IN r0 0x0000000000000000
  #_ REGISTER_IN r5 0x0000000010001002
  #_ REGISTER_IN r6 0x0000000000000003
  #_ REGISTER_IN r7 0x0000000011223344
  mtxer r6
  stswx r7, 0, r5
  blr
  #_ MEMORY_OUT 10001000 AAAA112233AAAAAA

test_stswx_zero:
  #_ MEMORY_IN 10001000 AAAAAAAAAAAAAAAA
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r5 0x0000000000000000
  #_ REGISTER_IN r6 0x0000000000000000
  #_ REGISTER_IN r7 0x0000000011223344
  mtxer r6
  stswx r7, r4, r5
  blr
  #_ MEMORY_OUT 10001000 AAAAAAAAAAAAAAAA

test_stswx_wrap:
  #_ MEMORY_IN 10001000 AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r5 0x0000000000000000
  #_ REGISTER_IN r6 0x000000000000000E
  #_ REGISTER_IN r30 0x0000000001020304
  #_ REGISTER_IN r31 0x0000000005060708
  #_ REGISTER_IN r0 0x00000000090A0B0C
  #_ REGISTER_IN r1 0x000000000D0E0F10
  mtxer r6
  stswx r30, r4, r5
  blr
  #_ MEMORY_OUT 10001000 0102030405060708090A0B0C0D0EAAAA
