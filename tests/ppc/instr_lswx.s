# Load string word: lswi (count in the instruction) and lswx (count in
# XER[57:63], set with mtxer). Xenia has neither, nor tests for them; these
# follow PowerPC Book I. Same format as Xenia's tests (src/xenia/cpu/ppc/testing).

test_lswi_1:
  #_ MEMORY_IN 10001000 0102030405060708090A0B0C
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r7 0xFFFFFFFFFFFFFFFF
  #_ REGISTER_IN r8 0xFFFFFFFFFFFFFFFF
  #_ REGISTER_IN r9 0xFFFFFFFFFFFFFFFF
  lswi r7, r4, 6
  blr
  #_ REGISTER_OUT r4 0x0000000010001000
  #_ REGISTER_OUT r7 0x0000000001020304
  #_ REGISTER_OUT r8 0x0000000005060000
  #_ REGISTER_OUT r9 0xFFFFFFFFFFFFFFFF

test_lswi_32:
  #_ MEMORY_IN 10001000 000102030405060708090A0B0C0D0E0F101112131415161718191A1B1C1D1E1F2021
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r15 0xFFFFFFFFFFFFFFFF
  lswi r7, r4, 0
  blr
  #_ REGISTER_OUT r7 0x0000000000010203
  #_ REGISTER_OUT r8 0x0000000004050607
  #_ REGISTER_OUT r9 0x0000000008090A0B
  #_ REGISTER_OUT r10 0x000000000C0D0E0F
  #_ REGISTER_OUT r11 0x0000000010111213
  #_ REGISTER_OUT r12 0x0000000014151617
  #_ REGISTER_OUT r13 0x0000000018191A1B
  #_ REGISTER_OUT r14 0x000000001C1D1E1F
  #_ REGISTER_OUT r15 0xFFFFFFFFFFFFFFFF

test_lswi_ra0:
  #_ MEMORY_IN 00000000 A1A2A3A4A5
  #_ MEMORY_IN 10001000 0102030405
  #_ REGISTER_IN r0 0x0000000010001000
  lswi r5, 0, 3
  blr
  #_ REGISTER_OUT r0 0x0000000010001000
  #_ REGISTER_OUT r5 0x00000000A1A2A300

test_lswi_wrap:
  #_ MEMORY_IN 10001000 0102030405060708090A0B0C
  #_ REGISTER_IN r4 0x0000000010001000
  lswi r30, r4, 9
  blr
  #_ REGISTER_OUT r30 0x0000000001020304
  #_ REGISTER_OUT r31 0x0000000005060708
  #_ REGISTER_OUT r0 0x0000000009000000

test_lswx_1:
  #_ MEMORY_IN 10001000 0102030405060708090A0B0C
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r5 0x0000000000000000
  #_ REGISTER_IN r6 0x0000000000000007
  #_ REGISTER_IN r7 0xFFFFFFFFFFFFFFFF
  #_ REGISTER_IN r8 0xFFFFFFFFFFFFFFFF
  #_ REGISTER_IN r9 0xFFFFFFFFFFFFFFFF
  mtxer r6
  lswx r7, r4, r5
  blr
  #_ REGISTER_OUT r4 0x0000000010001000
  #_ REGISTER_OUT r5 0x0000000000000000
  #_ REGISTER_OUT r7 0x0000000001020304
  #_ REGISTER_OUT r8 0x0000000005060700
  #_ REGISTER_OUT r9 0xFFFFFFFFFFFFFFFF

